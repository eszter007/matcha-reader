const char* DictIndex::vocabIdxPath() {
  return resolveIdxPath(g_vocabIdxResolved, VOCAB_IDX_PATH, JP_LEGACY_VOCAB_IDX_PATH, OLD_VOCAB_IDX_PATH,
                        LEGACY_VOCAB_IDX_PATH);
}
// Each .dat pairs with whichever .idx was resolved -- never mix legacy and preferred halves.
const char* DictIndex::vocabDatPath() { return datFor(vocabIdxPath(), g_vocabDat); }
const char* DictIndex::namesIdxPath() {
  return resolveIdxPath(g_namesIdxResolved, NAMES_IDX_PATH, JP_LEGACY_NAMES_IDX_PATH, OLD_NAMES_IDX_PATH,
                        LEGACY_NAMES_IDX_PATH);
}
const char* DictIndex::namesDatPath() { return datFor(namesIdxPath(), g_namesDat); }
const char* DictIndex::grammarIdxPath() {
  return resolveIdxPath(g_grammarIdxResolved, GRAMMAR_IDX_PATH, nullptr, OLD_GRAMMAR_IDX_PATH, nullptr);
}
const char* DictIndex::grammarDatPath() { return datFor(grammarIdxPath(), g_grammarDat); }

bool DictIndex::isAvailable() { return Storage.exists(vocabIdxPath()) && Storage.exists(vocabDatPath()); }

bool DictIndex::lookupInFile(const char* headword, const char* idxPath, const char* datPath, DictEntry& out,
                             bool needDefinition, uint8_t posMask) {
  DictFileHandles& h = handlesFor(idxPath);
  if (!h.opened) {
    // Optional dictionaries (grammar, jmnedict) may genuinely not be on the SD card -- without
    // this latch, every lookup attempt would retry the open (and its filesystem overhead) only to
    // fail again, once per candidate/window/character for the whole page.
    if (h.triedOpen) return false;
    h.triedOpen = true;
    if (!Storage.openFileForRead("DICT", idxPath, h.idxFile) || !Storage.openFileForRead("DICT", datPath, h.datFile)) {
      return false;
    }
    h.opened = true;
  }
  HalFile& idxFile = h.idxFile;
  HalFile& datFile = h.datFile;

  const size_t fileSize = idxFile.size();
  if (fileSize < sizeof(DictIndexRecord)) {
    return false;
  }

  const size_t recordCount = fileSize / sizeof(DictIndexRecord);

  // Build the RAM coarse tier from the .spx sidecar on first use for this dict.
  if (!h.spxTried) {
    h.spxTried = true;
    loadSpx(h, idxPath, recordCount);
  }

  char key[DictIndexRecord::HEADWORD_SIZE];
  std::memset(key, 0, sizeof(key));
  const size_t len = std::strlen(headword);
  if (len >= sizeof(key)) {
    return false;
  }
  std::memcpy(key, headword, len);

  size_t lo = 0;
  size_t hi = recordCount;
  // Narrow the [lo,hi) window with the two-tier sparse index when available -- turns the
  // ~log2(recordCount) scattered reads of the binary search below into a search over a single
  // SPX_STRIDE-record window (served from one block fetch). The window is guaranteed to contain
  // the key if it exists (see scripts/gen_dict_spx.py + its validation), but it does NOT pin down
  // WHICH record of a duplicate-headword run the search lands on: the narrowed and full searches
  // bisect different ranges and settle on different members of the same run. Everything the
  // cmp==0 branch below derives from that match is therefore anchored on the run itself (walked
  // back to its true first record), never on `mid` -- otherwise the two paths return different
  // answers for the same headword.
  if (h.spxOk) {
    size_t wlo, whi;
    if (spxNarrow(h, key, recordCount, wlo, whi)) {
      lo = wlo;
      hi = whi;
    }
  }
  DictIndexRecord rec;

  while (lo < hi) {
    const size_t mid = lo + (hi - lo) / 2;
    if (!readIndexRecord(h, mid, recordCount, rec)) {
      g_lookupIncomplete = true;
      break;
    }

    const int cmp = std::memcmp(key, rec.headword, DictIndexRecord::HEADWORD_SIZE);
    if (cmp < 0) {
      hi = mid;
    } else if (cmp > 0) {
      lo = mid + 1;
    } else {
      // POS gate: a record with flags counts only if it intersects the caller's mask; a record
      // with posFlags==0 (no POS data, e.g. a pre-flags dict file) always counts. posMask==0
      // means the caller doesn't care (exact surface-form lookups).
      const auto posAccept = [posMask](uint8_t flags) { return posMask == 0 || flags == 0 || (flags & posMask) != 0; };
      // Siblings retained for the priority ranking below (heap cost: 32 * 8 B).
      constexpr size_t kMaxSiblingScan = 32;
      // Hard bound on how far either walk below may travel, so a degenerate index (every record
      // sharing one headword) can't turn a lookup into a full-file scan. Far above the longest
      // run any real dictionary produces -- こう in the shipped jmdict is 54 records.
      constexpr size_t kMaxRunScan = 512;

      // Walk back to the FIRST record of this headword's run. `mid` is not a stable anchor: the
      // full and .spx-narrowed searches bisect different ranges and land on different members of
      // the same run, so any window measured from `mid` (as this used to be) selects a different
      // slice of a long run on each path and returns different definitions for the same word.
      // The run start is a property of the data, so both paths agree on it.
      // Normal runs are short and the walk stays inside the block cache readIndexRecord() just
      // centred on `mid` -- no extra SD reads. The binary-search fallback only runs when the
      // linear budget is exhausted, and keeps `first` exact even then.
      size_t first = mid;
      while (first > 0 && (mid - first) < kMaxRunScan) {
        DictIndexRecord prevRec;
        if (!readIndexRecord(h, first - 1, recordCount, prevRec)) {
          g_lookupIncomplete = true;
          break;
        }
        if (std::memcmp(key, prevRec.headword, DictIndexRecord::HEADWORD_SIZE) != 0) break;
        first--;
      }
      if (first > 0 && (mid - first) >= kMaxRunScan) {
        // Records are sorted, so every record before the run compares != key: bisect [0, first)
        // for the lowest index that still matches. ~log2(n) reads, for a run no real dict has.
        size_t blo = 0, bhi = first;
        while (blo < bhi) {
          const size_t bmid = blo + (bhi - blo) / 2;
          DictIndexRecord br;
          if (!readIndexRecord(h, bmid, recordCount, br)) {
            blo = first;  // read error: keep the linear result rather than guess
            break;
          }
          if (std::memcmp(key, br.headword, DictIndexRecord::HEADWORD_SIZE) == 0) {
            bhi = bmid;
          } else {
            blo = bmid + 1;
          }
        }
        first = blo;
      }
      const size_t scanEnd = std::min(recordCount, first + kMaxRunScan);

      // POS-filtered existence check: report the HIGHEST-priority compatible sibling in the run.
      // Reporting whichever record the search landed on was the other half of the path-dependence
      // bug -- out.priority reaches WordSelectionScan's kana-reading suppression gate
      // (WordSelectionScan.cpp:630), so a mid-dependent priority made a word's selectability
      // differ between the two search paths. Taking the maximum also matches what the
      // needDefinition=true path below reports (entries[0], the top-priority sibling).
      if (!needDefinition) {
        bool found = false;
        uint8_t bestPriority = 0;
        uint8_t bestPosFlags = 0;
        for (size_t idx = first; idx < scanEnd; idx++) {
          DictIndexRecord r;
          if (!readIndexRecord(h, idx, recordCount, r)) {
            g_lookupIncomplete = true;
            break;
          }
          if (std::memcmp(key, r.headword, DictIndexRecord::HEADWORD_SIZE) != 0) break;
          if (!posAccept(r.posFlags)) continue;
          if (!found || r.priority > bestPriority) {
            bestPriority = r.priority;
            bestPosFlags = r.posFlags;
            found = true;
          }
        }
        if (!found) return false;
        out.headword = headword;
        out.priority = bestPriority;
        out.posFlags = bestPosFlags;
        out.definition.clear();
        return true;
      }

      // Two passes so the highest-priority senses win even when they sit past the first few in
      // storage order. The index groups all same-reading records together but NOT by priority, so
      // a reading with many homophones (ほう: 方/法/報/...袍) could bury the common word (方) behind
      // rarer ones (袍) and the old "read the first 5, then sort those" lost it. Pass 1 walks the
      // whole run reading ONLY the index record (priority + payload location, no .dat read) and
      // ranks it; pass 2 reads definitions for just the top-priority few. Pass 1 is cheap
      // index-only SD reads; pass 2 does the same handful of .dat reads as before.
      struct Sib {
        uint8_t priority;
        uint8_t posFlags;
        uint32_t offset;
        uint16_t length;
      };
      std::vector<Sib> sibs;
      sibs.reserve(kMaxSiblingScan);
      for (size_t idx = first; idx < scanEnd; idx++) {
        DictIndexRecord r;
        if (!readIndexRecord(h, idx, recordCount, r)) {
          g_lookupIncomplete = true;
          break;
        }
        if (std::memcmp(key, r.headword, DictIndexRecord::HEADWORD_SIZE) != 0) break;
        if (!posAccept(r.posFlags)) continue;  // wrong word class for this deinflection candidate
        // Keep the top kMaxSiblingScan by PRIORITY across the whole run, inserting so the vector
        // stays ordered (priority desc, index order for ties). Cutting the run off at the first
        // kMaxSiblingScan records instead would reintroduce a position-dependent result on runs
        // longer than the cap, and the ranking is what the merge below actually needs.
        // Insert-into-sorted also removes the selection sort that used to follow this loop.
        size_t p = 0;
        while (p < sibs.size() && sibs[p].priority >= r.priority) p++;
        if (p >= kMaxSiblingScan) continue;  // ranks below everything already retained
        // pop first so the insert can never exceed the reserved capacity (no reallocation).
        if (sibs.size() == kMaxSiblingScan) sibs.pop_back();
        sibs.insert(sibs.begin() + static_cast<std::ptrdiff_t>(p), {r.priority, r.posFlags, r.offset, r.length});
      }
      if (sibs.empty()) return false;

      // Read definitions for the top-priority siblings, already in priority order.
      struct Entry {
        std::string def;
        uint8_t priority;
      };
      std::vector<Entry> entries;
      uint8_t bestFlags = 0;  // posFlags of the first (highest-priority) entry actually read
      constexpr int kMaxEntries = 5;
      for (size_t s = 0; s < sibs.size() && static_cast<int>(entries.size()) < kMaxEntries; s++) {
        // def.resize() is a bare allocation that abort()s on OOM under -fno-exceptions -- confirmed
        // by a real device crash_report with the heap run down mid-lookup-session. Skip entries
        // that don't comfortably fit (shorter definition instead of a reboot); the size cap also
        // rejects a corrupt/misread record length before it becomes a huge allocation request.
        constexpr uint32_t MAX_DEF_BYTES = 16 * 1024;
        if (sibs[s].length > MAX_DEF_BYTES || ESP.getMaxAllocHeap() < sibs[s].length + 8 * 1024) {
          g_heapLimited = true;
          g_lookupIncomplete = true;
          LOG_ERR("DICT", "Skipping entry (%u bytes, maxAlloc=%u)", static_cast<unsigned>(sibs[s].length),
                  ESP.getMaxAllocHeap());
          if (entries.empty()) continue;  // keep trying: a lower-priority sibling may be smaller
          break;
        }
        datFile.seek(sibs[s].offset);
        std::string def;
        def.resize(sibs[s].length);
        if (datFile.read(reinterpret_cast<uint8_t*>(def.data()), sibs[s].length) != static_cast<int>(sibs[s].length)) {
          g_lookupIncomplete = true;
          continue;
        }
        if (entries.empty()) bestFlags = sibs[s].posFlags;
        entries.push_back({std::move(def), sibs[s].priority});
      }

      if (entries.empty()) return false;

      out.headword = headword;
      out.priority = entries[0].priority;
      out.posFlags = bestFlags;
      if (entries.size() == 1) {
        out.definition = std::move(entries[0].def);
      } else {
        // Merge: show best entry, then separator + other entries. One guarded reserve and
        // plain appends -- the old `a + b` temporary chain doubled the peak allocation, and
        // under a tight heap the merge is droppable (the best entry alone is still useful).
        size_t mergedLen = 0;
        for (const auto& en : entries) mergedLen += en.def.size() + 8;
        if (ESP.getMaxAllocHeap() < mergedLen + 8 * 1024) {
          g_heapLimited = true;
          LOG_ERR("DICT", "Skipping entry merge, heap too low (maxAlloc=%u)", ESP.getMaxAllocHeap());
          out.definition = std::move(entries[0].def);
        } else {
          out.definition.reserve(mergedLen);
          out.definition = entries[0].def;
          for (size_t e = 1; e < entries.size(); e++) {
            out.definition += "\n\n---\n";
            out.definition += entries[e].def;
          }
        }
      }
      return true;
    }
  }

  return false;
}

namespace {
// --- Negative lookup memo ---------------------------------------------------------------------
// A page scan asks lookupExact() the same question over and over: WordLookup walks 8 window
// lengths per position and up to 64 deinflection candidates per window, and a position that
// matches nothing pays every one of them. Measured on one 125-character vertical page: 75,831
// lookupExact and 32,460 SD reads, ~230 s, during which the reader is unusable.
//
// Misses dominate that traffic, and a miss is stable for as long as the dictionary files stay
// open, so remembering one is free in correctness terms. Direct-mapped, one 64-bit fingerprint
// per slot over (headword, dictMask, posMask). needDefinition is deliberately NOT in the key: it
// changes what a HIT returns, never whether the headword exists.
//
// Only a lookup that actually established absence may be recorded. A search cut short by an SD
// read error, or one whose every candidate definition was skipped for want of heap, returns the
// same `false` but has proven nothing (g_lookupIncomplete marks it) -- memoizing that would make
// one transient failure the permanent answer for the rest of the lookup session.
//
// The 64-bit tag is what makes this safe. A tag collision would silently hide a real word; at
// this table's occupancy that is ~1e-10 across a whole page, where a 32-bit tag would be a
// near-certainty. The table is freed by releaseCaches() with the rest of the lookup state, so it
// never outlives a lookup session, and it is allocated lazily -- if the allocation fails under
// pressure the memo simply stays off.
constexpr size_t kMissMemoSlots = 1024;
std::unique_ptr<uint64_t[]> g_missMemo;

uint64_t missTagFor(const char* headword, const uint8_t dictMask, const uint8_t posMask) {
  uint64_t h = 1469598103934665603ull;
  for (const char* p = headword; *p; ++p) {
    h ^= static_cast<unsigned char>(*p);
    h *= 1099511628211ull;
  }
  h ^= dictMask;
  h *= 1099511628211ull;
  h ^= posMask;
  h *= 1099511628211ull;
  return h ? h : 1;  // 0 marks an empty slot, so no real key may be 0
}

void rememberMiss(const uint64_t tag) {
  if (!g_missMemo) {
    g_missMemo = makeUniqueNoThrow<uint64_t[]>(kMissMemoSlots);
    if (!g_missMemo) return;  // no memo under pressure; results are unaffected either way
    std::fill_n(g_missMemo.get(), kMissMemoSlots, 0ull);
  }
  g_missMemo[tag % kMissMemoSlots] = tag;
}
}  // namespace

bool DictIndex::lookupExact(const char* headword, DictEntry& out, uint8_t dictMask, bool needDefinition,
                            uint8_t posMask) {
  g_lookupExactCalls++;
  g_lookupIncomplete = false;
  const uint64_t missTag = missTagFor(headword, dictMask, posMask);
  if (g_missMemo && g_missMemo[missTag % kMissMemoSlots] == missTag) {
    g_missMemoHits++;
    return false;
  }
  // No Storage.exists() pre-checks needed here -- lookupInFile()'s own open-once cache already
  // makes a missing optional dictionary (grammar, jmnedict) a cheap no-op after the first attempt,
  // and an existence check would itself be a filesystem call repeated on every lookup otherwise.
  if ((dictMask & DICT_JMDICT) &&
      lookupInFile(headword, vocabIdxPath(), vocabDatPath(), out, needDefinition, posMask)) {
    out.sourceDict = DICT_JMDICT;
    return true;
  }
  if ((dictMask & DICT_GRAMMAR) &&
      lookupInFile(headword, grammarIdxPath(), grammarDatPath(), out, needDefinition, posMask)) {
    out.sourceDict = DICT_GRAMMAR;
    return true;
  }
  if ((dictMask & DICT_NAMES) && lookupInFile(headword, namesIdxPath(), namesDatPath(), out, needDefinition, posMask)) {
    out.sourceDict = DICT_NAMES;
    return true;
  }
  if (!g_lookupIncomplete) rememberMiss(missTag);
  return false;
}

bool DictIndex::consumeHeapLimited() {
  const bool limited = g_heapLimited;
  g_heapLimited = false;
  return limited;
}

void DictIndex::releaseCaches() {
  g_jpRootResolved.clear();  // re-probe /.dictionaries vs /dictionaries next session
  g_missMemo.reset();
  g_vocabHandles.release();
  g_grammarHandles.release();
  g_namesHandles.release();
  // Re-probe filenames next session: dictionary files can be added/replaced mid-session via the
  // web file transfer, including switching between legacy and preferred names.
  g_vocabIdxResolved = nullptr;
  g_namesIdxResolved = nullptr;
  g_grammarIdxResolved = nullptr;
  g_vocabDat.clear();
  g_namesDat.clear();
  g_grammarDat.clear();
}

void DictIndex::logAndResetStats(const char* label) {
  LOG_INF("DICT",
          "%s: %u lookupExact (%u memoized misses), idx %u hits/%u reads, fine %u hits/%u reads (total %u SD reads)",
          label, g_lookupExactCalls, g_missMemoHits, g_recordCacheHits, g_recordCacheMisses, g_fineHits, g_fineReads,
          g_recordCacheMisses + g_fineReads);
  g_lookupExactCalls = 0;
  g_missMemoHits = 0;
  g_recordCacheHits = 0;
  g_recordCacheMisses = 0;
  g_fineReads = 0;
  g_fineHits = 0;
}
