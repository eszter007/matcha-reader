// Re-opening the idx/dat files on every lookup was the dominant cost of building the Word Lookup
// screen: each SD file open has real filesystem overhead (path resolution, directory traversal),
// and WordLookup::lookup() calls DictIndex::lookupExact() up to 8 window lengths x several
// deinflection candidates x up to 3 dictionaries -- per character position on the page. For a
// full page that's thousands of opens where a handful would do. There are only ever 3 fixed
// (idx, dat) path pairs (jmdict/grammar/jmnedict) for the process's whole lifetime, so it's safe
// to open each pair once (lazily, on first use) and keep it open rather than reopening per call.
// ── Two-tier sparse index (.spx) ────────────────────────────────────────────
// A flat .idx is sorted 40-byte records; a plain binary search over the 600K+ record
// dictionaries costs ~20 scattered SD reads, and Word Lookup does thousands of lookups per
// page -> minutes of SD I/O. The .spx sidecar (generated by scripts/gen_dict_spx.py) is a
// coarse checkpoint layer: one 32-byte headword key per SPX_STRIDE .idx records. We keep a
// RAM sub-sample of those keys (the "coarse" tier, <=MAX_COARSE per dict) and binary-search
// it with ZERO reads to bracket the key into a small on-disk fine window; one read of that
// fine window narrows to a single SPX_STRIDE-record .idx block. Net: ~2 reads instead of ~20.
// Purely additive -- if the .spx is missing or its record count no longer matches the live
// .idx (dict was updated), spxOk stays false and lookupInFile() runs the full binary search.
constexpr uint8_t SPX_MAGIC[8] = {'C', 'P', 'S', 'P', 'X', '1', 0, 0};
constexpr uint32_t SPX_VERSION = 1;
constexpr size_t SPX_HEADER_SIZE = 32;
constexpr size_t SPX_KEY_SIZE = DictIndexRecord::HEADWORD_SIZE;  // 32
// MAX_COARSE balances two costs. Bigger -> more coarse entries in heap during the (memory-tight)
// scan; smaller -> bigger fine windows, and a big fine window is a slow SD read (transfer time,
// not just per-transaction overhead) that the fine-window cache below must then absorb. 128 keeps
// the coarse heap ~10KB (safe headroom under the resident reader) and the fine window ~4KB.
constexpr size_t MAX_COARSE = 128;         // RAM coarse entries per dict
constexpr size_t FINE_SLICE_BYTES = 3904;  // one coarse bracket (>= max cstride*32)

struct CoarseEntry {
  char key[SPX_KEY_SIZE];
  uint32_t fineIdx;  // index into the fine tier this key was sampled from
};

// ALL per-dict cache memory below lives on the HEAP, exact-sized, allocated lazily on first
// lookup and freed by DictIndex::releaseCaches() when the Word Lookup activity exits. It must
// not be static and must not linger: the reader keeps ~180KB resident, and heavy operations
// right after a lookup session (horizontal re-pagination needs a single contiguous 32KB block
// for the zip inflate dictionary) fail if the pool is ~30KB smaller or fragmented by long-lived
// mid-heap allocations. Rebuilding the caches on the next lookup costs only ~0.5s of the scan.

// Diagnostic counters (declared before the spx helpers that touch them). Temporary instrumentation
// for the Word Lookup slowness investigation; see DictIndex::logAndResetStats().
uint32_t g_lookupExactCalls = 0;
// Set when an entry (or a merge) was dropped purely because the heap could not hold it, so a
// caller can tell "this word has no definition" apart from "we could not load it right now".
bool g_heapLimited = false;
// Set when a search reached no verdict -- an .idx/.dat read failed, or every candidate definition
// was skipped for want of heap -- rather than establishing that the headword is absent. The
// difference matters only to the negative memo: recording such a lookup would state "this word
// does not exist" for the rest of the session on the strength of one bad moment, and would also
// answer the caller's release-fonts-and-retry from the memo before it could reach the SD card.
// Reset at the top of every lookupExact().
bool g_lookupIncomplete = false;
static uint32_t g_missMemoHits = 0;  // lookups answered from the negative memo (no SD traffic)
uint32_t g_recordCacheHits = 0;
uint32_t g_recordCacheMisses = 0;
uint32_t g_fineReads = 0;  // fine-window SD reads (spx tier)
uint32_t g_fineHits = 0;   // fine-window cache hits (no SD read)

struct DictFileHandles {
  HalFile idxFile;
  HalFile datFile;
  bool opened = false;
  bool triedOpen = false;  // true once an open has been attempted, success or failure

  // Read-ahead cache for the index-record accesses in lookupInFile() (heap; see block comment
  // above). Sized to hold a whole SPX_STRIDE (48) window plus slack, so once the spx has narrowed
  // to a window, a single block fetch serves the window search AND the collect walks. When the
  // allocation failed, readIndexRecord() falls back to direct single-record reads.
  static constexpr size_t BLOCK_RECORDS = 64;
  std::unique_ptr<DictIndexRecord[]> blockCache;
  bool blockCacheTried = false;
  size_t blockStart = SIZE_MAX;  // record index blockCache[0] corresponds to; SIZE_MAX = empty
  size_t blockCount = 0;         // valid records currently in blockCache

  // Sparse-index (.spx) state, populated lazily on first lookup for this dict.
  HalFile spxFile;
  bool spxTried = false;
  bool spxOk = false;
  uint32_t spxStride = 0;
  uint32_t spxFineCount = 0;
  uint32_t spxCStride = 0;
  size_t spxCoarseCount = 0;
  // Coarse tier: one sampled key per spxCStride fine entries, exact-sized (heap).
  std::unique_ptr<CoarseEntry[]> coarse;

  // One-slot cache of the last fine window read for this dict (heap, exact bracket size). A scan
  // position issues ~8 window lengths x several deinflection candidates into the SAME dict, all
  // sharing a leading prefix and thus usually the same coarse bracket -> the same fine window.
  // Caching it turns the per-lookup fine-window read (the dominant cost once the .idx reads are
  // gone) into a RAM hit for most of a position's probes. Per-dict (not shared) so the
  // jmdict/grammar/jmnedict interleaving within one lookupExact() doesn't thrash it.
  std::unique_ptr<uint8_t[]> fineCache;
  size_t fineCacheBytes = 0;          // allocated size (cstride * SPX_KEY_SIZE)
  uint32_t fineCacheLo = UINT32_MAX;  // fine index of fineCache[0]; UINT32_MAX = empty
  size_t fineCacheCount = 0;          // number of 32-byte keys currently cached

  // Free every cache and close every file, returning ALL memory to the pool. Next lookup relearns
  // lazily. Called via DictIndex::releaseCaches() when a Word Lookup activity exits.
  // NOTE: on device, calling ANY HalFile method (including close()) on a never-opened handle is an
  // assert -> panic, and a dict that was never consulted this session (e.g. jmnedict on a page
  // with no kanji/katakana) has never-opened handles -- so every close MUST be isOpen()-guarded.
  void release() {
    if (idxFile.isOpen()) idxFile.close();
    if (datFile.isOpen()) datFile.close();
    if (spxFile.isOpen()) spxFile.close();
    opened = false;
    triedOpen = false;
    blockCache.reset();
    blockCacheTried = false;
    blockStart = SIZE_MAX;
    blockCount = 0;
    spxTried = false;
    spxOk = false;
    coarse.reset();
    fineCache.reset();
    fineCacheBytes = 0;
    fineCacheLo = UINT32_MAX;
    fineCacheCount = 0;
  }
};

DictFileHandles g_vocabHandles;
DictFileHandles g_grammarHandles;
DictFileHandles g_namesHandles;

// Classified by filename, not full path: the folder is resolved at runtime (/dictionaries/jp,
// /.dictionaries/jp or /dict), so only the leaf is fixed.
DictFileHandles& handlesFor(const char* idxPath) {
  const char* slash = std::strrchr(idxPath, '/');
  const char* leaf = slash ? slash + 1 : idxPath;
  if (std::strcmp(leaf, "grammar.idx") == 0) return g_grammarHandles;
  if (std::strcmp(leaf, "names.idx") == 0 || std::strcmp(leaf, "jmnedict.idx") == 0) return g_namesHandles;
  return g_vocabHandles;
}

// Resolved idx path for the vocab/names pairs: preferred filename if present on the SD card,
// else legacy. nullptr = not probed yet. Cleared by DictIndex::releaseCaches() so dictionary
// files uploaded mid-session (web file transfer) are picked up by the next lookup session.
const char* g_vocabIdxResolved = nullptr;
const char* g_namesIdxResolved = nullptr;
const char* g_grammarIdxResolved = nullptr;
// The .dat paired with each resolved .idx. Same folder and stem, so derived from it rather than
// from a constant: the folder may be /.dictionaries/jp, which no constant spells.
std::string g_vocabDat;
std::string g_namesDat;
std::string g_grammarDat;

const char* datFor(const char* idxPath, std::string& cache) {
  if (cache.empty()) {
    cache = idxPath;
    const size_t len = cache.size();
    if (len > 4 && cache.compare(len - 4, 4, ".idx") == 0) cache.replace(len - 4, 4, ".dat");
  }
  return cache.c_str();
}

// The folder the Japanese dictionary lives in. Two spellings are accepted, the same way the font
// registry accepts /.fonts beside /fonts: the dotted one keeps the folder out of the file browser
// (hidden by default) and is preferred when both exist. Resolved once and cleared by
// releaseCaches(), so a dictionary uploaded mid-session into the other root is picked up next
// session rather than never.
std::string g_jpRootResolved;

const char* jpRoot() {
  if (g_jpRootResolved.empty()) {
    g_jpRootResolved = Storage.exists("/.dictionaries/jp") ? "/.dictionaries/jp" : "/dictionaries/jp";
  }
  return g_jpRootResolved.c_str();
}

// A DictIndex path constant rewritten under the resolved root. The constants stay full paths
// because a host-side tool reads them directly; only the folder half is substituted here.
std::string underJpRoot(const char* path) {
  const char* leaf = strrchr(path, '/');
  return std::string(jpRoot()) + (leaf ? leaf : "/");
}

// Storage.exists() on the path as it will actually be opened -- under the resolved root.
bool existsUnderRoot(const char* path, std::string& out) {
  out = underJpRoot(path);
  return Storage.exists(out.c_str());
}

const char* resolveIdxPath(const char*& cache, const char* preferred, const char* jpLegacy, const char* old,
                           const char* legacy) {
  if (cache) return cache;
  // Probed under the resolved root; the winner is interned so the returned pointer stays valid.
  static std::vector<std::unique_ptr<std::string>> interned;
  std::string candidate;
  const auto intern = [](std::string&& v) -> const char* {
    interned.push_back(std::unique_ptr<std::string>(new (std::nothrow) std::string(std::move(v))));
    return interned.back() ? interned.back()->c_str() : nullptr;
  };
  for (const char* p : {preferred, jpLegacy, old, legacy}) {
    if (!p) continue;
    if (existsUnderRoot(p, candidate)) {
      if (const char* held = intern(std::move(candidate))) {
        if (p == legacy) LOG_INF("DICT", "Using legacy dictionary filename: %s", held);
        cache = held;
        return cache;
      }
      break;  // OOM interning: fall through to the plain paths below
    }
  }
  if (Storage.exists(preferred)) {
    cache = preferred;
  } else if (jpLegacy && Storage.exists(jpLegacy)) {
    cache = jpLegacy;
  } else if (Storage.exists(old)) {
    cache = old;
  } else if (legacy && Storage.exists(legacy)) {
    LOG_INF("DICT", "Using legacy dictionary filename: %s", legacy);
    cache = legacy;
  } else {
    // Neither present: cache the preferred name anyway. Leaving this case un-cached would
    // re-run both exists() probes inside EVERY lookupExact() when an optional dict (names) is
    // absent -- thousands of SD probes per page scan, where the pre-rename code paid nothing
    // (lookupInFile's triedOpen cache). Tradeoff: files uploaded mid-session are noticed at
    // the next lookup session (releaseCaches() clears this cache AND the triedOpen latches)
    // or reboot. isAvailable() alone reflects a preferred-named upload immediately, since it
    // re-runs exists() on the resolved path; a legacy-named upload needs the re-probe.
    cache = preferred;
  }
  return cache;
}

// Derive "/dict/foo.spx" from "/dict/foo.idx" into out (must be >= strlen(idxPath)+1).
// Returns false if idxPath doesn't end in ".idx".
bool spxPathFor(const char* idxPath, char* out, size_t outSize) {
  const size_t len = std::strlen(idxPath);
  if (len < 4 || len + 1 > outSize) return false;
  if (std::memcmp(idxPath + len - 4, ".idx", 4) != 0) return false;
  std::memcpy(out, idxPath, len + 1);
  std::memcpy(out + len - 4, ".spx", 4);
  return true;
}

// The coarse tier is sampled from keys scattered the whole length of the .spx, so building it
// costs one seek+read per entry -- 128 of them per dictionary, and seek latency dominates
// (measured: 177ms jmdict, 192ms jmnedict, 38ms grammar at 15 coarse; ~400ms of a ~613ms Word
// Lookup open). The keys only change when the .spx does, so cache them next to it and read the
// whole tier back in ONE sequential read. Purely additive: a missing, stale or unreadable sidecar
// just falls back to the scattered build, which then rewrites it.
constexpr uint8_t SPXC_MAGIC[8] = {'C', 'P', 'S', 'P', 'C', '1', 0, 0};
constexpr size_t SPXC_HEADER_SIZE = 24;  // magic(8) + fineCount + cstride + coarseCount + entrySize

bool spxcPathFor(const char* idxPath, char* out, size_t outSize) {
  const size_t len = std::strlen(idxPath);
  // len + 1 (not + 2): the copy below writes exactly len+1 bytes including the NUL, and the
  // suffix swapped in is the same 4 chars as the one it replaces. Requiring an extra byte
  // needlessly disabled the sidecar for paths that fit exactly.
  if (len < 4 || len + 1 > outSize) return false;
  if (std::memcmp(idxPath + len - 4, ".idx", 4) != 0) return false;
  std::memcpy(out, idxPath, len + 1);
  std::memcpy(out + len - 4, ".spc", 4);
  return true;
}

// One read of the whole coarse tier. False = no usable sidecar; caller builds it the slow way.
bool loadCoarseSidecar(const char* idxPath, CoarseEntry* coarse, uint32_t fineCount, uint32_t cstride,
                       size_t coarseCount) {
  char path[64];
  if (!spxcPathFor(idxPath, path, sizeof(path))) return false;
  HalFile f;
  if (!Storage.openFileForRead("DICT", path, f)) return false;
  uint8_t header[SPXC_HEADER_SIZE];
  if (f.read(header, SPXC_HEADER_SIZE) != static_cast<int>(SPXC_HEADER_SIZE)) return false;
  if (std::memcmp(header, SPXC_MAGIC, sizeof(SPXC_MAGIC)) != 0) return false;
  uint32_t gotFine, gotCStride, gotCount, gotEntry;
  std::memcpy(&gotFine, header + 8, 4);
  std::memcpy(&gotCStride, header + 12, 4);
  std::memcpy(&gotCount, header + 16, 4);
  std::memcpy(&gotEntry, header + 20, 4);
  // Every field the tier's meaning depends on: a regenerated .spx changes fineCount, and a
  // different build of the firmware could change the entry layout.
  if (gotFine != fineCount || gotCStride != cstride || gotCount != coarseCount || gotEntry != sizeof(CoarseEntry)) {
    return false;
  }
  const size_t bytes = coarseCount * sizeof(CoarseEntry);
  return f.read(reinterpret_cast<uint8_t*>(coarse), bytes) == static_cast<int>(bytes);
}

void saveCoarseSidecar(const char* idxPath, const CoarseEntry* coarse, uint32_t fineCount, uint32_t cstride,
                       size_t coarseCount) {
  char path[64];
  if (!spxcPathFor(idxPath, path, sizeof(path))) return;
  HalFile f;
  if (!Storage.openFileForWrite("DICT", path, f)) return;
  uint8_t header[SPXC_HEADER_SIZE];
  std::memset(header, 0, sizeof(header));
  std::memcpy(header, SPXC_MAGIC, sizeof(SPXC_MAGIC));
  const uint32_t entrySize = sizeof(CoarseEntry);
  const uint32_t count32 = static_cast<uint32_t>(coarseCount);
  std::memcpy(header + 8, &fineCount, 4);
  std::memcpy(header + 12, &cstride, 4);
  std::memcpy(header + 16, &count32, 4);
  std::memcpy(header + 20, &entrySize, 4);
  if (f.write(header, SPXC_HEADER_SIZE) != static_cast<int>(SPXC_HEADER_SIZE)) return;
  const size_t bytes = coarseCount * sizeof(CoarseEntry);
  f.write(reinterpret_cast<const uint8_t*>(coarse), bytes);
}

// Load and validate the .spx sidecar for h, building the RAM coarse tier. Sets h.spxOk.
// Safe to leave spxOk=false on any inconsistency -- lookupInFile() then does a full search.
void loadSpx(DictFileHandles& h, const char* idxPath, size_t recordCount) {
  char spxPath[64];
  if (!spxPathFor(idxPath, spxPath, sizeof(spxPath))) return;
  if (!Storage.openFileForRead("DICT", spxPath, h.spxFile)) return;

  uint8_t header[SPX_HEADER_SIZE];
  if (h.spxFile.read(header, SPX_HEADER_SIZE) != static_cast<int>(SPX_HEADER_SIZE)) return;
  if (std::memcmp(header, SPX_MAGIC, sizeof(SPX_MAGIC)) != 0) return;
  uint32_t version, stride, idxCount, fineCount;
  std::memcpy(&version, header + 8, 4);
  std::memcpy(&stride, header + 12, 4);
  std::memcpy(&idxCount, header + 16, 4);
  std::memcpy(&fineCount, header + 20, 4);
  if (version != SPX_VERSION || stride == 0 || fineCount == 0) return;
  // Stale sidecar (dict file changed) -> fall back to the full search rather than mis-locate.
  if (idxCount != recordCount) {
    LOG_ERR("DICT", "spx %s stale: %u records vs idx %u", spxPath, idxCount, static_cast<unsigned>(recordCount));
    return;
  }

  const uint32_t cstride = (fineCount + MAX_COARSE - 1) / MAX_COARSE;
  // One coarse bracket spans cstride fine entries; that whole slice must fit the scratch buffer.
  if (static_cast<size_t>(cstride) * SPX_KEY_SIZE > FINE_SLICE_BYTES) return;
  const size_t coarseCount = (fineCount + cstride - 1) / cstride;

  auto coarse = makeUniqueNoThrow<CoarseEntry[]>(coarseCount);
  const size_t fineBytes = static_cast<size_t>(cstride) * SPX_KEY_SIZE;
  auto fineCache = makeUniqueNoThrow<uint8_t[]>(fineBytes);
  if (!coarse || !fineCache) {
    // Not enough contiguous heap right now -> stay on the full search. Not fatal.
    LOG_ERR("DICT", "spx alloc failed (%u coarse, %u B fine); using full search", static_cast<unsigned>(coarseCount),
            static_cast<unsigned>(fineBytes));
    return;
  }
  if (!loadCoarseSidecar(idxPath, coarse.get(), fineCount, cstride, coarseCount)) {
    for (size_t c = 0; c < coarseCount; c++) {
      const uint32_t fineIdx = static_cast<uint32_t>(c) * cstride;  // < fineCount by construction
      h.spxFile.seek(SPX_HEADER_SIZE + static_cast<size_t>(fineIdx) * SPX_KEY_SIZE);
      if (h.spxFile.read(reinterpret_cast<uint8_t*>(coarse[c].key), SPX_KEY_SIZE) != static_cast<int>(SPX_KEY_SIZE)) {
        return;  // partial -> leave spxOk false
      }
      coarse[c].fineIdx = fineIdx;
    }
    // Only a COMPLETE tier is cached: a partial build returned above, so reaching here means
    // every key was read.
    saveCoarseSidecar(idxPath, coarse.get(), fineCount, cstride, coarseCount);
  }

  h.coarse = std::move(coarse);
  h.fineCache = std::move(fineCache);
  h.fineCacheBytes = fineBytes;
  h.fineCacheLo = UINT32_MAX;
  h.fineCacheCount = 0;
  h.spxStride = stride;
  h.spxFineCount = fineCount;
  h.spxCStride = cstride;
  h.spxCoarseCount = coarseCount;
  h.spxOk = true;
  LOG_INF("DICT", "spx %s: %u checkpoints, %u coarse in RAM (%u B)", spxPath, fineCount,
          static_cast<unsigned>(coarseCount), static_cast<unsigned>(coarseCount * sizeof(CoarseEntry)));
}

// Narrow the search to the .idx record window [*lo,*hi) that must contain `key` (a 32-byte,
// null-padded headword) if present. Zero-read coarse RAM search + one fine-window read.
// Returns false (caller keeps [0,recordCount)) on any read error.
bool spxNarrow(DictFileHandles& h, const char* key, size_t recordCount, size_t& lo, size_t& hi) {
  // 1) Coarse RAM binary search: largest ci with coarse[ci].key <= key.
  size_t clo = 0, chi = h.spxCoarseCount;
  while (clo < chi) {
    const size_t mid = clo + (chi - clo) / 2;
    if (std::memcmp(h.coarse[mid].key, key, SPX_KEY_SIZE) <= 0) {
      clo = mid + 1;
    } else {
      chi = mid;
    }
  }
  const size_t ci = (clo > 0) ? clo - 1 : 0;
  const uint32_t fLo = h.coarse[ci].fineIdx;
  const uint32_t fHi = (ci + 1 < h.spxCoarseCount) ? h.coarse[ci + 1].fineIdx : h.spxFineCount;
  const size_t sliceCount = fHi - fLo;
  if (sliceCount == 0 || sliceCount * SPX_KEY_SIZE > h.fineCacheBytes || !h.fineCache) return false;

  // 2) Fetch the fine slice (from the one-slot cache when the coarse bracket is unchanged),
  //    then binary-search it in RAM: largest f with fine[fLo+f] <= key.
  if (h.fineCacheLo != fLo || h.fineCacheCount != sliceCount) {
    g_fineReads++;
    h.spxFile.seek(SPX_HEADER_SIZE + static_cast<size_t>(fLo) * SPX_KEY_SIZE);
    const size_t bytes = sliceCount * SPX_KEY_SIZE;
    if (h.spxFile.read(h.fineCache.get(), bytes) != static_cast<int>(bytes)) {
      h.fineCacheLo = UINT32_MAX;  // invalidate on partial read
      return false;
    }
    h.fineCacheLo = fLo;
    h.fineCacheCount = sliceCount;
  } else {
    g_fineHits++;
  }
  size_t flo = 0, fhi = sliceCount;
  while (flo < fhi) {
    const size_t mid = flo + (fhi - flo) / 2;
    if (std::memcmp(h.fineCache.get() + mid * SPX_KEY_SIZE, key, SPX_KEY_SIZE) <= 0) {
      flo = mid + 1;
    } else {
      fhi = mid;
    }
  }
  const size_t f = fLo + ((flo > 0) ? flo - 1 : 0);
  lo = f * h.spxStride;
  hi = std::min(recordCount, (f + 1) * static_cast<size_t>(h.spxStride));
  return true;
}

// Reads index record `idx` (of `recordCount` total), transparently using/filling h's block cache.
// Semantically identical to a direct seek+read of that one record -- callers don't need to know
// whether this was served from cache or SD.
bool readIndexRecord(DictFileHandles& h, size_t idx, size_t recordCount, DictIndexRecord& out) {
  if (h.blockCache && h.blockStart != SIZE_MAX && idx >= h.blockStart && idx < h.blockStart + h.blockCount) {
    out = h.blockCache[idx - h.blockStart];
    g_recordCacheHits++;
    return true;
  }
  g_recordCacheMisses++;

  if (!h.blockCache && !h.blockCacheTried) {
    h.blockCacheTried = true;
    h.blockCache = makeUniqueNoThrow<DictIndexRecord[]>(DictFileHandles::BLOCK_RECORDS);
  }
  if (!h.blockCache) {
    // No cache memory available -- direct single-record read still works, just slower.
    h.idxFile.seek(idx * sizeof(DictIndexRecord));
    return h.idxFile.read(reinterpret_cast<uint8_t*>(&out), sizeof(DictIndexRecord)) ==
           static_cast<int>(sizeof(DictIndexRecord));
  }

  const size_t half = DictFileHandles::BLOCK_RECORDS / 2;
  const size_t start = (idx > half) ? (idx - half) : 0;
  const size_t count = std::min(DictFileHandles::BLOCK_RECORDS, recordCount - start);

  h.idxFile.seek(start * sizeof(DictIndexRecord));
  const size_t bytesToRead = count * sizeof(DictIndexRecord);
  if (h.idxFile.read(reinterpret_cast<uint8_t*>(h.blockCache.get()), bytesToRead) != static_cast<int>(bytesToRead)) {
    h.blockStart = SIZE_MAX;  // invalidate on read failure -- don't serve a partial block later
    return false;
  }

  h.blockStart = start;
  h.blockCount = count;
  out = h.blockCache[idx - start];
  return true;
}
