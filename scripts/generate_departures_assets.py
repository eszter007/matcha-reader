#!/usr/bin/env python3
"""Generate the lettering of the Departures sleep screen as run-length coded bitmaps.

The screen is a split-flap board, set in a condensed face the firmware has no font for, so its
fixed words and the ten digits are pre-rendered instead of shipping font tables. The words are a
deliberate design element in English and Japanese and are not translated.

    python3 scripts/generate_departures_assets.py --latin BarlowCondensed-SemiBold.ttf \
        --japanese NotoSansCJKjp-Bold.otf

Barlow Condensed: https://github.com/google/fonts/tree/main/ofl/barlowcondensed (SIL OFL).
Noto Sans CJK JP Bold: lib/EpdFont/scripts/downloaded_fonts/NotoSansJP (SIL OFL).

Writes src/images/DeparturesType.h.
"""
import argparse
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent

# The flap digits per tile height (DEP_TILE_H in SleepActivity.cpp, regular and compact), and the
# pixel size that fills that tile.
DIGIT_SETS = [("DepDigits", 90, 94), ("DepDigitsCompact", 68, 71)]

# (C name, text, font, pixel size, letter spacing)
WORDS = [
    ("DepWordDepartures", "DEPARTURES", "latin", 30, 5),
    ("DepWordShuppatsu", "出発", "japanese", 30, 0),
    ("DepWordHoursRead", "HOURS READ", "latin", 22, 4),
    ("DepWordDayStreak", "DAY STREAK", "latin", 22, 4),
    ("DepWordMinutesThisWeek", "MINUTES THIS WEEK", "latin", 22, 4),
    ("DepWordNext", "NEXT", "latin", 19, 4),
    ("DepWordOneMore", "ONE MORE", "latin", 52, 1),
    ("DepWordChapter", "CHAPTER", "latin", 52, 1),
]


def render(text, font, spacing):
    """Black-on-white lettering cropped to its ink, as a 1-bit image."""
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    width = sum(probe.textlength(ch, font=font) + spacing for ch in text)
    ascent, descent = font.getmetrics()
    img = Image.new("L", (int(width) + 8, ascent + descent + 8), 255)
    draw = ImageDraw.Draw(img)
    x = 4
    for ch in text:
        draw.text((x, 4), ch, font=font, fill=0)
        x += probe.textlength(ch, font=font) + spacing
    bw = img.point(lambda v: 0 if v < 128 else 255)
    box = bw.point(lambda v: 255 - v).getbbox()
    return bw.crop(box)


def pack(img):
    """1 bit per pixel, ink = 1, MSB first, each row starting on a byte."""
    out = bytearray()
    for y in range(img.height):
        for x0 in range(0, img.width, 8):
            byte = 0
            for k in range(8):
                ink = x0 + k < img.width and img.getpixel((x0 + k, y)) == 0
                byte = byte << 1 | int(ink)
            out.append(byte)
    return bytes(out)


def c_array(data, per_line=19):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + per_line]) + ",")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--latin", type=Path, required=True, help="BarlowCondensed-SemiBold.ttf")
    parser.add_argument("--japanese", type=Path, required=True, help="NotoSansCJKjp-Bold.otf")
    args = parser.parse_args()
    fonts = {"latin": args.latin, "japanese": args.japanese}

    blob = bytearray()
    words = []
    for name, text, face, size, spacing in WORDS:
        img = render(text, ImageFont.truetype(str(fonts[face]), size), spacing)
        words.append(f"// {text}\nstatic constexpr DepartureBitmap {name} = {{{img.width}, {img.height}, {len(blob)}}};")
        blob += pack(img)
    digit_tables = []
    for table_name, tile_h, digit_px in DIGIT_SETS:
        digit_font = ImageFont.truetype(str(args.latin), digit_px)
        table = []
        for d in range(10):
            img = render(str(d), digit_font, 0)
            table.append(f"    {{{img.width}, {img.height}, {len(blob)}}},")
            blob += pack(img)
        digit_tables.append(f"// The flap digits 0-9 for a tile {tile_h} px tall.\n"
                            f"static constexpr DepartureBitmap {table_name}[10] = {{\n" + "\n".join(table) + "\n};")
    compressor = zlib.compressobj(level=9, wbits=-15)
    deflated = compressor.compress(bytes(blob)) + compressor.flush()

    header = (
        "#pragma once\n#include <cstdint>\n\n"
        "// Lettering of the Departures sleep screen, pre-rendered in Barlow Condensed SemiBold and Noto Sans\n"
        "// CJK JP Bold (both SIL Open Font License). All bitmaps share one raw-deflate stream; inflated it\n"
        "// holds each at its offset, 1 bit per pixel, ink = 1, MSB first, every row starting on a byte.\n"
        "// Generated by scripts/generate_departures_assets.py.\n\n"
        "struct DepartureBitmap {\n  uint16_t width;\n  uint16_t height;\n  uint16_t offset;\n};\n\n"
        f"static constexpr uint16_t DEP_TYPE_INFLATED_SIZE = {len(blob)};\n"
        f"static const uint8_t DepTypeDeflated[] = {{\n{c_array(deflated)}\n}};\n\n"
    )
    out = ROOT / "src" / "images" / "DeparturesType.h"
    out.write_text(header + "\n".join(words) + "\n\n" + "\n\n".join(digit_tables) + "\n")
    print(f"wrote {out}: {len(blob)} bytes inflated, {len(deflated)} deflated")


if __name__ == "__main__":
    main()
